-- =============================================================================
-- 012_stratum_sync.sql — Stratum split-plane: versioning + sync + metrics
-- =============================================================================
-- Applies on top of existing schema (001-011).
-- Idempotent: uses IF NOT EXISTS and column guards where applicable.
--
-- What it adds:
--   1. Global monotonic sequence for differential DP ↔ CP sync
--   2. version + updated_at columns on policies and users (api_key_hash)
--   3. Triggers that auto-bump version on each UPDATE
--   4. data_plane_instances — registry of data plane instances
--   5. stratum_metrics — metrics received from the data plane
-- =============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Global sequence — monotonic, increments on each write to policies/users
-- ---------------------------------------------------------------------------

CREATE SEQUENCE IF NOT EXISTS stratum_version_seq
  START 1
  INCREMENT 1
  NO CYCLE;

-- ---------------------------------------------------------------------------
-- 2. Columns on policies
-- ---------------------------------------------------------------------------
-- The policies table has at least: id, team_id, allowed_models, etc.
-- We add version + updated_at. If they already exist, ALTER is a no-op via guard.

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'policies' AND column_name = 'version'
  ) THEN
    ALTER TABLE policies
      ADD COLUMN version    BIGINT       NOT NULL DEFAULT nextval('stratum_version_seq'),
      ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
  END IF;
END $$;

-- Backfill: assign unique versions to existing rows that landed on DEFAULT 1
-- (in case the table was populated before this migration)
UPDATE policies
SET version = nextval('stratum_version_seq')
WHERE version = 1 AND ctid NOT IN (
  SELECT min(ctid) FROM policies GROUP BY version
);

-- ---------------------------------------------------------------------------
-- 3. Columns on users (api_key_hash lives here in Stratum v1)
-- ---------------------------------------------------------------------------
-- Stratum treats each api_key as a separately versioned object.
-- We add version + revoked + revoked_at so the DP can distinguish
-- "new key" from "revoked key".

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'users' AND column_name = 'key_version'
  ) THEN
    ALTER TABLE users
      ADD COLUMN key_version    BIGINT       NOT NULL DEFAULT nextval('stratum_version_seq'),
      ADD COLUMN key_revoked    BOOLEAN      NOT NULL DEFAULT false,
      ADD COLUMN key_revoked_at TIMESTAMPTZ;
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 4. Trigger functions and triggers for auto-bump
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION stratum_bump_policy_version()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.version    := nextval('stratum_version_seq');
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_policies_version ON policies;
CREATE TRIGGER trg_policies_version
  BEFORE UPDATE ON policies
  FOR EACH ROW
  EXECUTE FUNCTION stratum_bump_policy_version();

-- For users (only when api_key_hash, revoked, or policy-relevant fields change)
CREATE OR REPLACE FUNCTION stratum_bump_key_version()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  -- Only bump if something relevant to the DP changed
  IF NEW.api_key_hash IS DISTINCT FROM OLD.api_key_hash OR
     NEW.key_revoked  IS DISTINCT FROM OLD.key_revoked  OR
     NEW.team_id      IS DISTINCT FROM OLD.team_id
  THEN
    NEW.key_version := nextval('stratum_version_seq');
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_users_key_version ON users;
CREATE TRIGGER trg_users_key_version
  BEFORE UPDATE ON users
  FOR EACH ROW
  EXECUTE FUNCTION stratum_bump_key_version();

-- ---------------------------------------------------------------------------
-- 5. data_plane_instances — one row per registered data plane instance
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS data_plane_instances (
  id              TEXT        PRIMARY KEY,           -- "dp_{uuid}" — generated by CP at registration
  org_id          UUID        NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  name            TEXT        NOT NULL,              -- human-readable (e.g. "prod-vpc-us-east")
  sync_token_hash TEXT        NOT NULL UNIQUE,       -- SHA-256(sync_token) — raw token never stored
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at    TIMESTAMPTZ,                       -- last successful DP sync
  last_version    BIGINT      NOT NULL DEFAULT 0,    -- last current_version the DP received
  disabled        BOOLEAN     NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_dp_instances_org   ON data_plane_instances(org_id);
CREATE INDEX IF NOT EXISTS idx_dp_instances_token ON data_plane_instances(sync_token_hash);

-- ---------------------------------------------------------------------------
-- 6. stratum_metrics — metrics received from the data plane
-- ---------------------------------------------------------------------------
-- Zero prompt content. Only aggregated metadata per time window.

CREATE TABLE IF NOT EXISTS stratum_metrics (
  id                BIGSERIAL     PRIMARY KEY,
  instance_id       TEXT          NOT NULL REFERENCES data_plane_instances(id) ON DELETE CASCADE,
  received_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),

  -- Aggregation time window
  window_start      TIMESTAMPTZ   NOT NULL,
  window_end        TIMESTAMPTZ   NOT NULL,

  -- Routing dimensions
  team_id           TEXT          NOT NULL,
  model             TEXT          NOT NULL,
  provider          TEXT,

  -- Counters
  req_count         INT           NOT NULL DEFAULT 1,
  prompt_tokens     BIGINT        NOT NULL DEFAULT 0,
  completion_tokens BIGINT        NOT NULL DEFAULT 0,
  cost_usd          DECIMAL(12,6) NOT NULL DEFAULT 0,
  error_count       INT           NOT NULL DEFAULT 0
);

-- Dashboard indexes
CREATE INDEX IF NOT EXISTS idx_stratum_metrics_instance ON stratum_metrics(instance_id, received_at DESC);
CREATE INDEX IF NOT EXISTS idx_stratum_metrics_team     ON stratum_metrics(team_id, window_start DESC);
CREATE INDEX IF NOT EXISTS idx_stratum_metrics_window   ON stratum_metrics(window_start, window_end);

-- ---------------------------------------------------------------------------
-- Convenience views for the dashboard
-- ---------------------------------------------------------------------------

-- View: usage by team in the current month (DP data)
CREATE OR REPLACE VIEW v_stratum_team_usage_current_month AS
SELECT
  team_id,
  model,
  provider,
  SUM(req_count)         AS total_requests,
  SUM(prompt_tokens)     AS total_prompt_tokens,
  SUM(completion_tokens) AS total_completion_tokens,
  SUM(cost_usd)          AS total_cost_usd,
  SUM(error_count)       AS total_errors,
  MIN(window_start)      AS first_request,
  MAX(window_end)        AS last_request
FROM stratum_metrics
WHERE window_start >= date_trunc('month', now())
GROUP BY team_id, model, provider;

-- View: active instances (seen in the last 5 minutes)
CREATE OR REPLACE VIEW v_stratum_active_instances AS
SELECT
  dpi.*,
  o.name AS org_name,
  EXTRACT(EPOCH FROM (now() - dpi.last_seen_at))::INT AS seconds_since_sync
FROM data_plane_instances dpi
JOIN organizations o ON o.id = dpi.org_id
WHERE dpi.disabled = false
  AND dpi.last_seen_at > now() - INTERVAL '5 minutes';

COMMIT;
